SEC_E_ANCHOR = "- **Урок:** для генерации временных меток МСК в `fixes/` использовать стандартный `datetime.timezone(datetime.timedelta(hours=3))` вместо `zoneinfo.ZoneInfo`."
SEC_E_NEW = SEC_E_ANCHOR + """

### DL-63. Обрыв длинных кодовых блоков в Markdown при генерации патч-скриптов
- **Когда:** выдача патч-скрипта длиной > 200 строк с вложенным кодом в `'''...'''` или `base64`.
- **Симптом:** парсер Markdown обрывал кодовый блок посередине, часть кода выпадала в обычный текст, терялись отступы и символы умножения `*`.
- **Первопричина:** ограничение длины/парсинга одного кодового блока в интерфейсе и конфликт вложенных кавычек/звёздочек.
- **Исправление:** в `Rules.md` (v2.1, §2.2) добавлено правило разбиения скриптов длиннее 100 строк на последовательные блоки (`# --- Часть 1/N ---`, `# --- Часть 2/N ---`), а также приоритет точечных diff-патчей (`str.replace`) вместо перезаписи всего файла.
- **Урок:** не выдавать кодовые блоки длиннее 100 строк; использовать точечные замены или разбивать код на части по ≤ 100 строк."""

HIST_OLD = "| 3.7 | DL-60 (исправление упрощённой модели FMCN1476), DL-61 (`timezone(timedelta(hours=3))` вместо `ZoneInfo` и путь `TRL_script/`) |"
HIST_NEW = (
    "| 3.7 | DL-60 (исправление упрощённой модели FMCN1476), DL-61 (`timezone(timedelta(hours=3))` вместо `ZoneInfo` и путь `TRL_script/`) |\n"
    "| 3.8 | DL-62 (ориентация футпринта FMCN1476, пад R=0.28 / вырез R=0.50, 12 via, окно 1.50×0.55 мм, `bot_cut_dia`), DL-63 (разбиение кодовых блоков ≤ 100 строк) |"
)

def apply_patch():
    if not TARGET.exists():
        raise FileNotFoundError(f"Файл не найден: {TARGET}")
    text = TARGET.read_text(encoding="utf-8")
    old_count = len(text.splitlines())
    if "### DL-62." in text and "### DL-63." in text:
        print(f"[{ts} MSK] {TARGET.name}: изменений не требуется (идемпотентность).")
        return
    updated = (
        text.replace(CHRONO_OLD, CHRONO_NEW)
            .replace(SEC_A_ANCHOR, SEC_A_NEW)
            .replace(SEC_E_ANCHOR, SEC_E_NEW)
            .replace(HIST_OLD, HIST_NEW)
    )
    TARGET.write_text(updated, encoding="utf-8")
    new_count = len(updated.splitlines())
    print(f"[{ts} MSK] === {TARGET} ===")
    print(f"  Было строк: {old_count}")
    print(f"  Стало строк: {new_count} ({new_count - old_count:+d})")
    print("  ✓ применено: добавлены записи DL-62 и DL-63 (версия 3.8).")

if __name__ == "__main__":
    apply_patch()
