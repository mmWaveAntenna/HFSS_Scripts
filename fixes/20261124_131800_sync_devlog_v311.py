def apply_patch():
    text = TARGET.read_text(encoding="utf-8")
    old_count = len(text.splitlines())
    if text.startswith("markdown\n"):
        text = text[len("markdown\n"):]
    for h in ("Раздел D. API, парсинг, HFSS-операции", "Раздел E. Процесс и окружение", "Приложение. Отозванные советы", "История документа"):
        text = text.replace(f"\n{h}\n", f"\n## {h}\n")
    for line in CHRONO_ENTRIES:
        dl_id = line.split("|")[1].strip()
        if f"| {dl_id} |" not in text:
            text = text.replace("## Раздел A. Физика, топология, параметризация", line + "\n\n---\n\n## Раздел A. Физика, топология, параметризация", 1)
    if "### DL-67." not in text:
        text = text.replace("## Раздел D. API, парсинг, HFSS-операции", SEC_A_RECS.strip() + "\n\n---\n\n## Раздел D. API, парсинг, HFSS-операции", 1)
    if "### DL-69." not in text:
        text = text.replace("## Раздел E. Процесс и окружение", SEC_D_RECS.strip() + "\n\n---\n\n## Раздел E. Процесс и окружение", 1)
    if "### DL-66." not in text:
        text = text.replace("## Приложение. Отозванные советы", SEC_E_RECS.strip() + "\n\n---\n\n## Приложение. Отозванные советы", 1)
    for hl in HIST_LINES:
        ver = hl.split("|")[1].strip()
        if f"| {ver} |" not in text:
            text = text.rstrip() + "\n" + hl + "\n"
    TARGET.write_text(text.rstrip() + "\n", encoding="utf-8")
    new_count = len(text.rstrip().splitlines())
    print(f"[{ts} MSK] === {TARGET} ===\n  Было строк: {old_count}\n  Стало строк: {new_count} ({new_count - old_count:+d})")

if __name__ == "__main__":
    apply_patch()
